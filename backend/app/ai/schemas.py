"""Pydantic models for validating AI agent responses.

These schemas define the expected structure of responses from each AI agent.
They are used to parse and validate the JSON returned by the LLM, ensuring
consistent data flows through the system.
"""

from pydantic import BaseModel, Field, field_validator
from enum import Enum


# --- Code Reviewer schemas ---


class CodeReviewResult(BaseModel):
    """Result of the Code_Reviewer agent analysis."""

    fortalezas: list[str] = Field(
        ..., description="List of code strengths identified"
    )
    debilidades: list[str] = Field(
        ..., description="List of code weaknesses/improvement areas identified"
    )


# --- Ticket Generator schemas ---


class Prioridad(str, Enum):
    alta = "alta"
    media = "media"
    baja = "baja"


class Dificultad(str, Enum):
    facil = "fácil"
    media = "media"
    dificil = "difícil"


class TicketData(BaseModel):
    """A single improvement ticket generated by the Ticket_Generator agent."""

    titulo: str = Field(..., max_length=120, description="Ticket title")
    descripcion: str = Field(..., description="Detailed description of the improvement")
    prioridad: Prioridad = Field(..., description="Priority level")
    dificultad: Dificultad = Field(..., description="Difficulty level")
    tiempo_estimado_minutos: int = Field(
        ..., ge=15, le=480, description="Estimated time in minutes (15-480)"
    )


class TicketGenerationResult(BaseModel):
    """Result of the Ticket_Generator agent — exactly 3 tickets."""

    tickets: list[TicketData] = Field(..., min_length=3, max_length=3)


# --- Tech Lead schemas ---


class TechLeadResult(BaseModel):
    """Result of the Tech_Lead agent — 2 to 3 interview questions."""

    preguntas: list[str] = Field(..., min_length=2, max_length=3)


# --- Evaluator schemas ---


class DimensionScore(BaseModel):
    """Score for a single evaluation dimension (0-20 points)."""

    dimension: str = Field(..., description="Name of the dimension evaluated")
    puntaje: int = Field(..., ge=0, le=20, description="Score 0-20")
    comentario: str = Field(..., description="Brief comment about performance in this dimension")


class EvaluationResult(BaseModel):
    """Result of the Evaluator agent — detailed feedback with 5 dimensions."""

    feedback: str = Field(..., max_length=3000, description="General constructive feedback")
    aprobado: bool = Field(..., description="Whether the answers are approved (calificacion >= 70)")
    calificacion: int = Field(..., ge=0, le=100, description="Overall score 0-100 (sum of 5 dimensions)")
    aspectos_evaluados: list[DimensionScore] = Field(..., min_length=5, max_length=5, description="5 dimension scores")
    conceptos_a_mejorar: list[str] = Field(..., description="Concepts the developer should study further")
